import { Message, FileAttachment, UserRole } from "../types";

export interface AnalyzeQueryResponse {
  text: string;
  source: 'local_rag' | 'gemini_fallback' | 'error';
  confidence_score: number;
  citations: string[];
}

export class LegalAIService {
  private apiUrl: string = '/api/chat';

  /**
   * Communicates with the FastAPI Agentic Router endpoint (/api/chat).
   * Passes the user query, conversation history, and user persona role.
   * Handles 15-second timeouts and network errors with a graceful fallback.
   */
  async analyzeQuery(
    query: string,
    history: Message[],
    role: UserRole,
    attachments: FileAttachment[] = []
  ): Promise<AnalyzeQueryResponse> {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 15000);

    try {
      const response = await fetch(this.apiUrl, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        signal: controller.signal,
        body: JSON.stringify({
          query,
          history: history.map((h) => ({
            role: h.role,
            content: h.content,
            id: h.id,
          })),
          role,
        }),
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorData = await response.json().catch(() => null);
        throw new Error(
          errorData?.detail || `FastAPI backend responded with HTTP status ${response.status}`
        );
      }

      const data = await response.json();
      return {
        text: data.text || "No response generated by the legal engine.",
        source: data.source || 'gemini_fallback',
        confidence_score: typeof data.confidence_score === 'number' ? data.confidence_score : 0.85,
        citations: Array.isArray(data.citations) ? data.citations : [],
      };
    } catch (error: any) {
      clearTimeout(timeoutId);
      console.warn("FastAPI Router connection error (fallback triggered):", error);

      const isTimeout = error.name === 'AbortError';
      const errorMessage = isTimeout
        ? "⚠️ **Request Timeout**: The legal inference engine took longer than 15 seconds to respond. Please verify your connection or retry your query."
        : `⚠️ **Connection Error**: Unable to reach the Python FastAPI backend at \`${this.apiUrl}\`. Please ensure the FastAPI server is running via \`uvicorn backend.main:app --port 8000\`.`;

      return {
        text: errorMessage,
        source: 'error',
        confidence_score: 0.0,
        citations: [],
      };
    }
  }
}
